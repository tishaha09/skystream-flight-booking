// Fallback to process.env.MONGODB_URI if set
if (process.env.MONGODB_URI) {
  mongoUri = process.env.MONGODB_URI;
}

const isReset = process.argv.includes("--reset") || process.argv.includes("-r");

// Model definitions for seeding
const userSchema = new mongoose.Schema(
  {
    name: { type: String, required: true },
    email: { type: String, required: true, unique: true, lowercase: true },
    password: { type: String, required: true, select: false },
    phone: { type: String, default: "" },
    role: { type: String, enum: ["user", "admin"], default: "user" },
  },
  { timestamps: true }
);

const flightSchema = new mongoose.Schema(
  {
    airline: { type: String, required: true },
    flightNumber: { type: String, required: true, unique: true, uppercase: true },
    source: { type: String, required: true },
    sourceCode: { type: String, default: "DEL" },
    destination: { type: String, required: true },
    destinationCode: { type: String, default: "BOM" },
    departureDate: { type: String, required: true },
    departureTime: { type: String, required: true },
    arrivalTime: { type: String, required: true },
    duration: { type: String, required: true },
    stops: { type: String, default: "Non-stop" },
    aircraft: { type: String, default: "Airbus A320neo" },
    terminal: { type: String, default: "T3" },
    gate: { type: String, default: "14A" },
    price: { type: Number, required: true },
    totalSeats: { type: Number, required: true, default: 60 },
    availableSeats: { type: Number, required: true, default: 60 },
    travelClass: {
      type: String,
      enum: ["Economy", "Premium Economy", "Business", "First Class"],
      default: "Economy",
    },
    status: {
      type: String,
      enum: ["scheduled", "delayed", "cancelled", "completed"],
      default: "scheduled",
    },
    baggageInformation: { type: String, default: "Check-in: 15kg, Cabin: 7kg" },
  },
  { timestamps: true }
);
flightSchema.index({ source: 1, destination: 1, departureDate: 1 });
flightSchema.index({
  airline: "text",
  flightNumber: "text",
  source: "text",
  destination: "text",
});

const seatSchema = new mongoose.Schema(
  {
    flight: { type: mongoose.Schema.Types.ObjectId, ref: "Flight", required: true },
    seatNumber: { type: String, required: true },
    seatClass: { type: String, default: "Economy" },
    status: { type: String, enum: ["available", "booked"], default: "available" },
    booking: { type: mongoose.Schema.Types.ObjectId, ref: "Booking", default: null },
  },
  { timestamps: true }
);
seatSchema.index({ flight: 1, seatNumber: 1 }, { unique: true });

const passengerSchema = new mongoose.Schema(
  {
    booking: { type: mongoose.Schema.Types.ObjectId, ref: "Booking", required: true },
    name: { type: String, required: true },
    age: { type: Number, required: true },
    gender: { type: String, enum: ["Male", "Female", "Other"], required: true },
    email: { type: String, default: "" },
    phone: { type: String, default: "" },
    idNumber: { type: String, required: true },
    seatNumber: { type: String, default: "" },
  },
  { timestamps: true }
);

const bookingSchema = new mongoose.Schema(
  {
    user: { type: mongoose.Schema.Types.ObjectId, ref: "User", required: true },
    flight: { type: mongoose.Schema.Types.ObjectId, ref: "Flight", required: true },
    passengers: [{ type: mongoose.Schema.Types.ObjectId, ref: "Passenger" }],
    selectedSeats: [{ type: String, required: true }],
    fareType: { type: String, default: "Regular" },
    fareBreakdown: {
      baseFare: { type: Number, default: 0 },
      discountPercent: { type: Number, default: 0 },
      discountAmount: { type: Number, default: 0 },
      totalAmount: { type: Number, default: 0 },
    },
    totalAmount: { type: Number, required: true },
    bookingStatus: {
      type: String,
      enum: ["confirmed", "pending", "cancelled", "completed"],
      default: "confirmed",
    },
    bookingDate: { type: Date, default: Date.now },
  },
  { timestamps: true }
);

const notificationSchema = new mongoose.Schema(
  {
    user: { type: mongoose.Schema.Types.ObjectId, ref: "User", required: true },
    message: { type: String, required: true },
    type: { type: String, enum: ["booking", "flight", "system"], default: "booking" },
    isRead: { type: Boolean, default: false },
  },
  { timestamps: true }
);

const User = mongoose.model("User", userSchema);
const Flight = mongoose.model("Flight", flightSchema);
const Seat = mongoose.model("Seat", seatSchema);
const Passenger = mongoose.model("Passenger", passengerSchema);
const Booking = mongoose.model("Booking", bookingSchema);
const Notification = mongoose.model("Notification", notificationSchema);

